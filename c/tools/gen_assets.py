"""Turn the fonts and sprites under c/assets into C tables.

    python c/tools/gen_assets.py

Writes c/src/assets/assets.c and assets.h. Needs Pillow. The output is
committed, so building the firmware never needs Python; run this only after
adding or changing art.

Fonts are rasterised at the size each Kenney font was drawn for, where every
pixel is fully on or off. Sprites become 8-bit indexed images with their own
RGB565 palette; index 0 is transparent (alpha under 128).
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "assets")
OUT = os.path.join(ROOT, "src", "assets")

FONTS = [
    # C name, file, pixel size, extra pixels between glyphs
    ("font_mini", "fonts/Kenney Mini.ttf", 8, 0),
    ("font_blocks", "fonts/Kenney Blocks.ttf", 8, 1),
]

TILE = 16
TINY = "kenney/tiny_dungeon.png"
TINY_COLS = 12

# C name, source, optional (x, y, w, h) crop
SPRITES = [(f"spr_battler_{n}", f"battlers/{n}.png", None) for n in (
    "04", "06", "08", "11", "12", "15", "16", "17", "18", "19", "20", "22", "23", "25", "26", "27", "28", "29")]


def tiny(name, index):
    return (name, TINY, ((index % TINY_COLS) * TILE, (index // TINY_COLS) * TILE, TILE, TILE))


SPRITES += [
    tiny("spr_hero", 88),
    tiny("spr_sword", 104),
    tiny("spr_potion_red", 115),
    tiny("spr_potion_blue", 116),
    tiny("spr_chest", 89),
    tiny("spr_coin", 101),
]

# Pico Quest (rpg.c): the camp's shopkeeper and the armour icon.
SPRITES += [
    tiny("spr_wizard", 84),
    tiny("spr_shield", 66),
]


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def font_tables(cname, path, size, spacing):
    font = ImageFont.truetype(os.path.join(ASSETS, path), size)
    _, top, _, bottom = font.getbbox("HgjpqyQ|()[]")
    height = bottom - top
    widths, offsets, rows = [], [], []
    for code in range(32, 127):
        ch = chr(code)
        advance = int(round(font.getlength(ch)))
        img = Image.new("L", (advance + 8, height + 8), 0)
        ImageDraw.Draw(img).text((0, -top), ch, font=font, fill=255)
        ink = img.getbbox()
        width = max(advance, ink[2] if ink else 0)
        offsets.append(len(rows))
        for y in range(height):
            bits = 0
            for x in range(min(width, 16)):
                if img.getpixel((x, y)) > 127:
                    bits |= 1 << x
            rows.append(bits)
        widths.append(width + spacing if code != 32 else max(advance, size // 2))
    out = [f"static const uint8_t {cname}_widths[] = {{{', '.join(map(str, widths))}}};",
           f"static const uint16_t {cname}_offsets[] = {{{', '.join(map(str, offsets))}}};",
           f"static const uint16_t {cname}_rows[] = {{{', '.join(map(str, rows))}}};",
           f"const font_t {cname} = {{{height}, 32, 126, {cname}_widths, {cname}_offsets, {cname}_rows}};", ""]
    return out


def sprite_tables(cname, path, crop):
    img = Image.open(os.path.join(ASSETS, path)).convert("RGBA")
    if crop:
        x, y, w, h = crop
        img = img.crop((x, y, x + w, y + h))
    palette = [0]
    index = {}
    pixels = []
    for r, g, b, a in img.get_flattened_data() if hasattr(img, "get_flattened_data") else img.getdata():
        if a < 128:
            pixels.append(0)
            continue
        c = rgb565(r, g, b)
        if c not in index:
            if len(palette) == 256:
                sys.exit(f"{path} has more than 255 colours")
            index[c] = len(palette)
            palette.append(c)
        pixels.append(index[c])
    lines = [f"static const uint16_t {cname}_pal[] = {{{', '.join(f'0x{c:04X}' for c in palette)}}};",
             f"static const uint8_t {cname}_px[] = {{"]
    for i in range(0, len(pixels), 32):
        lines.append("    " + ",".join(map(str, pixels[i:i + 32])) + ",")
    lines += ["};", f"const sprite_t {cname} = {{{img.width}, {img.height}, {cname}_pal, {cname}_px}};", ""]
    return lines


def main():
    os.makedirs(OUT, exist_ok=True)
    body = ["// Generated by c/tools/gen_assets.py from c/assets. Do not edit.", '#include "assets.h"', ""]
    header = ["// Generated by c/tools/gen_assets.py. Do not edit.", "#pragma once", "",
              '#include "../core/gfx.h"', ""]
    for cname, path, size, spacing in FONTS:
        body += font_tables(cname, path, size, spacing)
    for cname, path, crop in SPRITES:
        body += sprite_tables(cname, path, crop)
        header.append(f"extern const sprite_t {cname};")
    with open(os.path.join(OUT, "assets.c"), "w", newline="\n") as f:
        f.write("\n".join(body))
    with open(os.path.join(OUT, "assets.h"), "w", newline="\n") as f:
        f.write("\n".join(header) + "\n")
    print(f"wrote {len(FONTS)} fonts and {len(SPRITES)} sprites to {OUT}")


if __name__ == "__main__":
    main()
